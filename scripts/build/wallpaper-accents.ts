// ADMIN-B47 (ADR 0037): computes the accent of every built-in wallpaper with the same pure function
// the server runs on an upload, and writes them into src/ui/tokens.css as static rules between its
// BEGIN and END wallpaper-accent markers. Run it again after adding or replacing a photograph in
// public/wallpapers/:
//   pnpm exec tsx scripts/build/wallpaper-accents.ts
// It decodes the photographs with sharp, the same library the server uses on an upload.
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import sharp from 'sharp';
import { Wallpaper } from '../../src/core/config/wallpapers';
import {
  accentGrounds,
  accentProperties,
  accentTokens,
  contrast,
  pickAccent,
} from '../../src/core/config/wallpaper-accent';

const root = process.cwd();
const side = 64;

async function picked(name: Wallpaper) {
  const pixels = await sharp(join(root, 'public/wallpapers', `${name}.jpg`))
    .resize(side, side, { fit: 'fill' })
    .ensureAlpha()
    .raw()
    .toBuffer();
  return pickAccent(pixels);
}
const begin = '/* BEGIN wallpaper accents: generated by scripts/build/wallpaper-accents.ts. */';
const end = '/* END wallpaper accents */';
const rules: string[] = [];
for (const name of Wallpaper.options) {
  const colour = await picked(name);
  const tokens = accentTokens(colour);
  const declarations = Object.entries(accentProperties(tokens))
    .map(([property, value]) => `  ${property}: ${value};`)
    .join('\n');
  rules.push(`/* ${name}: picked ${colour ?? 'nothing (sage)'} */\nhtml[data-wallpaper='${name}'] {\n${declarations}\n}`);
  const ratios = [
    ...accentGrounds.night.map((g) => contrast(tokens.night.accent, g)),
    ...accentGrounds.paper.map((g) => contrast(tokens.paper.accent, g)),
    contrast(tokens.night.onAccent, tokens.night.accent),
    contrast(tokens.paper.onAccent, tokens.paper.accent),
  ].map((r) => r.toFixed(2));
  process.stdout.write(
    `${name}\t${colour ?? 'sage'}\t${tokens.night.accent}\t${tokens.paper.accent}\t${ratios.join(' ')}\n`,
  );
}
const target = join(root, 'src/ui/tokens.css');
const css = await readFile(target, 'utf8');
const from = css.indexOf(begin);
const to = css.indexOf(end);
if (from < 0 || to < from) throw new Error(`tokens.css has no ${begin} … ${end} block`);
await writeFile(target, `${css.slice(0, from)}${begin}\n${rules.join('\n')}\n${css.slice(to)}`);
